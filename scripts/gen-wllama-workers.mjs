// Generates the static worker files that Manifest V3 requires, from the pinned @wllama/wllama package.
// Mirrors ProxyToWorker.moduleInit() in @wllama/wllama/src/worker.ts. The regular build goes to public/wllama/, which
// both the extension and the web app ship. The compatibility build, for browsers without JSPI or Memory64 (Safari
// before 27), comes from @wllama/wllama-compat at the same version and goes to web/wllama/, which only the web build
// copies: Chrome has both features and never asks for it, and the extension zip stays 15 MB lighter.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const pkgRoot = dirname(require.resolve('@wllama/wllama/package.json'));
const pkg = JSON.parse(readFileSync(join(pkgRoot, 'package.json'), 'utf8'));
const compatRoot = dirname(require.resolve('@wllama/wllama-compat/package.json'));
const compatPkg = JSON.parse(readFileSync(join(compatRoot, 'package.json'), 'utf8'));
if (compatPkg.version !== pkg.version) throw new Error(`gen-wllama-workers: @wllama/wllama-compat ${compatPkg.version} must match @wllama/wllama ${pkg.version}`);

const generated = readFileSync(join(pkgRoot, 'src/workers-code/generated.ts'), 'utf8');
const workerTs = readFileSync(join(pkgRoot, 'src/worker.ts'), 'utf8');

function constant(name) {
  const m = generated.match(new RegExp(`export const ${name} = ("(?:[^"\\\\]|\\\\.)*");`));
  if (!m) throw new Error(`gen-wllama-workers: ${name} not found in generated.ts`);
  return JSON.parse(m[1]);
}
function must(haystack, needle, what) {
  if (!haystack.includes(needle)) throw new Error(`gen-wllama-workers: expected ${what}`);
}

const LLAMA_CPP_WORKER_CODE = constant('LLAMA_CPP_WORKER_CODE');
const OPFS_UTILS_WORKER_CODE = constant('OPFS_UTILS_WORKER_CODE');
const WLLAMA_EMSCRIPTEN_CODE = constant('WLLAMA_EMSCRIPTEN_CODE');
const jspi = workerTs.match(/const JSPI_STUB = `([\s\S]*?)`;/);
if (!jspi) throw new Error('gen-wllama-workers: JSPI_STUB not found in worker.ts');
const JSPI_STUB = jspi[1];

// Same prefix wllama uses when n_gpu_layers is 0, so ggml-webgpu skips device registration.
const NO_WEBGPU_STUB =
  'try{Object.defineProperty(WorkerNavigator.prototype,"gpu",{get:()=>({requestAdapter:async()=>null})});}catch(e){}';

// pthread workers are spawned by emscripten from `mainScriptUrlOrBlob`. wllama passes a Blob;
// we pass the URL of the static module file instead so the spawn is CSP-clean.
must(LLAMA_CPP_WORKER_CODE, '? argMainScriptBlob', 'llama-cpp.js to reference argMainScriptBlob');
const llamaWorkerBody = LLAMA_CPP_WORKER_CODE.replace('? argMainScriptBlob', '? RUN_OPTIONS.moduleUrl');

/** The inference worker and the pthread entry for one emscripten glue: the regular build, or the compat one. */
function emit(dir, glue, suffix, from) {
  mkdirSync(dir, { recursive: true });
  const moduleCode = JSPI_STUB + glue;
  must(moduleCode, 'var Module', `${from} to declare \`var Module\``);
  const mainModuleCode = moduleCode.replace('var Module', 'var ___Module');
  const llamaWorker = [
    `// Generated by scripts/gen-wllama-workers.mjs from ${from}. Do not edit.`,
    `const RUN_OPTIONS = JSON.parse(new URLSearchParams(self.location.search).get("o") || "{}");`,
    `function wModuleInit() { if (RUN_OPTIONS.noWebGPU) { ${NO_WEBGPU_STUB} } ${mainModuleCode}; return Module; }`,
    llamaWorkerBody,
  ].join(';\n\n');
  writeFileSync(join(dir, `llama-worker${suffix}.js`), llamaWorker);
  writeFileSync(join(dir, `module${suffix}.js`), `// Generated from ${from}. pthread entry.\n` + moduleCode);
}

const out = join(process.cwd(), 'public', 'wllama');
emit(out, WLLAMA_EMSCRIPTEN_CODE, '', `@wllama/wllama ${pkg.version}`);
writeFileSync(join(out, 'opfs-worker.js'), `// Generated from @wllama/wllama ${pkg.version}.\n` + OPFS_UTILS_WORKER_CODE);
copyFileSync(join(pkgRoot, 'esm/wasm/wllama.wasm'), join(out, 'wllama.wasm'));
writeFileSync(join(out, 'VERSION'), pkg.version + '\n');

const webOut = join(process.cwd(), 'web', 'wllama');
emit(webOut, readFileSync(join(compatRoot, 'wasm/wllama.js'), 'utf8'), '-compat', `@wllama/wllama-compat ${compatPkg.version}`);
copyFileSync(join(compatRoot, 'wasm/wllama.wasm'), join(webOut, 'wllama-compat.wasm'));
writeFileSync(join(webOut, 'VERSION-compat'), compatPkg.version + '\n');

console.log(`gen-wllama-workers: wrote public/wllama/{llama-worker.js,module.js,opfs-worker.js,wllama.wasm} from @wllama/wllama ${pkg.version}, and web/wllama/{llama-worker-compat.js,module-compat.js,wllama-compat.wasm} from @wllama/wllama-compat ${compatPkg.version}`);
